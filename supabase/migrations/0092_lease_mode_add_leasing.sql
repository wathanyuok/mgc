-- 0092 — เพิ่มชนิดสัญญาเช่าตัวที่ 3 ให้ lease_mode
--
-- เดิม lease_mode มี 2 ค่า: 'hp' (เช่าซื้อ) กับ 'other' (สัญญาเช่า)
-- แล้วใช้ boolean use_bank_loan แยกย่อยว่า 'other' ตัวไหนใช้สินเชื่อธนาคาร
-- ที่ประชุมให้ยกตัวแยกย่อยนั้นขึ้นมาเป็นชนิดเต็มตัว รวมเป็น 3 ชนิด:
--   hp    = Hire Purchase  — ใช้วงเงินธนาคาร · กรรมสิทธิ์โอนให้ผู้เช่าซื้อปลายทาง
--   lease = Leasing        — ใช้วงเงินธนาคาร · กรรมสิทธิ์ยังเป็นของผู้ให้เช่า
--   other = Leasing Other  — ไม่ใช้วงเงินธนาคาร · เช่าที่ดิน อาคาร โกดัง
--
-- หมายเหตุ PostgreSQL: ค่า enum ที่เพิ่งเพิ่มจะใช้ใน statement เดียวกันไม่ได้
-- จึงต้องแยกไฟล์ — ไฟล์นี้เพิ่มค่าอย่างเดียว ส่วนการย้ายข้อมูลอยู่ที่ 0093

ALTER TYPE lease_mode ADD VALUE IF NOT EXISTS 'lease';
