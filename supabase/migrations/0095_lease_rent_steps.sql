-- 0095 — ค่าเช่าไม่เท่ากันตลอดอายุสัญญา
--
-- ที่ประชุมระบุว่าสัญญาเช่าจริงค่าเช่ามักไม่เท่ากันทุกงวด
-- เช่น ปีแรกเดือนละ 200,000 ช่วงปลายสัญญาขึ้นเป็น 260,000
-- ระบบเดิมรองรับค่าเช่าเท่ากันทุกงวดอย่างเดียว
--
-- เก็บเป็นรายการช่วงงวด — งวดที่เริ่ม · งวดที่จบ · ค่าเช่าต่อเดือนในช่วงนั้น
--   [{ "from_period": 1, "to_period": 12, "amount": 200000 },
--    { "from_period": 13, "to_period": 36, "amount": 260000 }]
--
-- ว่าง = ค่าเช่าเท่ากันทุกงวด (คำนวณจากเงินต้นแบบเดิม)

ALTER TABLE leases ADD COLUMN IF NOT EXISTS rent_steps JSONB;

COMMENT ON COLUMN leases.rent_steps IS
  'ค่าเช่าแยกตามช่วงงวด — ว่างหมายถึงค่าเช่าเท่ากันทุกงวด';
