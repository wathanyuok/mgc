/**
 * แปลง error ที่ได้จากการบันทึกเป็นข้อความภาษาคน
 * ถ้าไม่ใช่ข้อผิดพลาดที่รู้จัก จะคืนข้อความเดิมกลับไป
 */
export function friendlySaveError(e: unknown): string {
  const msg = String((e as any)?.message ?? e ?? '');

  if (/duplicate key|already exists|unique constraint/i.test(msg)) {
    for (const [re, text] of UNIQUE_FIELD_MESSAGES) {
      if (re.test(msg)) return text;
    }
    return 'ข้อมูลนี้ซ้ำกับรายการที่มีอยู่แล้ว — ตรวจเลขที่รายการหรือชื่อรายการอีกครั้ง';
  }

  // ข้อมูลอ้างอิงถูกใช้อยู่ ลบหรือแก้ไม่ได้
  if (/violates foreign key constraint/i.test(msg)) {
    return 'รายการนี้ถูกอ้างอิงอยู่ในรายการอื่น — ต้องเอาการอ้างอิงออกก่อน';
  }
  // ช่องบังคับในฐานข้อมูลยังว่าง
  if (/null value in column "(.+?)"/i.test(msg)) {
    const col = msg.match(/null value in column "(.+?)"/i)?.[1] ?? '';
    return `ยังกรอกข้อมูลไม่ครบ${col ? ` (ช่อง ${col})` : ''} — ตรวจช่องที่มีจุดแดงอีกครั้ง`;
  }
  // ค่าที่ส่งไปไม่อยู่ในรายการที่ระบบรู้จัก
  if (/invalid input value for enum/i.test(msg)) {
    return 'ค่าที่เลือกไม่ตรงกับรายการที่ระบบรู้จัก — เลือกใหม่จากรายการที่มีให้';
  }
  // ตัวเลขยาวเกินที่ช่องเก็บได้
  if (/numeric field overflow|value too long/i.test(msg)) {
    return 'ค่าที่กรอกยาวหรือมากเกินกว่าที่ช่องนี้เก็บได้';
  }

  return msg;
}
