// ตัดอักขระที่เป็น "ไวยากรณ์" ของตัวกรองออกจากคำค้นของผู้ใช้
//
// ตัวกรองแบบ .or() รับเงื่อนไขหลายชุดคั่นด้วยจุลภาค เช่น
//   code.ilike.%คำค้น%,name.ilike.%คำค้น%
// ถ้าผู้ใช้พิมพ์จุลภาคเข้ามาเอง คำค้นจะกลายเป็นเงื่อนไขชุดใหม่
//   พิมพ์  a,active.eq.false  →  ระบบอ่านเป็น 5 เงื่อนไข แทนที่จะเป็น 3
//   ผลคือเห็นรายการที่ถูกปิดใช้งาน ซึ่งไม่ควรเห็น
//
// อ่านอย่างเดียวจึงแก้/ลบข้อมูลไม่ได้ แต่ดึงข้อมูลเกินสิทธิ์ได้ — ต้องกัน
export function sanitizeSearch(raw: string, maxLen = 100): string {
  return raw
    .trim()
    .slice(0, maxLen)          // กันคำค้นยาวผิดปกติ
    .replace(/[,()*\\]/g, ' ') // , ( ) = ไวยากรณ์ตัวกรอง · * \ = ไวยากรณ์ ilike
    .replace(/\s+/g, ' ')
    .trim();
}
