// ═══════════════════════════════════════════════════════════════════
//  คำค้นของผู้ใช้ต้องแทรกเงื่อนไขเพิ่มเข้าไปในตัวกรองไม่ได้
//
//  ตัวกรองแบบ .or() รับเงื่อนไขหลายชุดคั่นด้วยจุลภาค — ถ้าปล่อยให้ผู้ใช้
//  พิมพ์จุลภาคเข้ามา คำค้นจะกลายเป็นเงื่อนไขชุดใหม่ และเห็นข้อมูลเกินสิทธิ์
// ═══════════════════════════════════════════════════════════════════
import { describe, it, expect } from 'vitest';
import { sanitizeSearch } from '@/lib/search-sanitize';

describe('คำค้น — กันการแทรกเงื่อนไข', () => {
  it.each([
    ['a,active.eq.false', 'จุลภาค — ตัวคั่นเงื่อนไข'],
    ['a)or(active.eq.false', 'วงเล็บ — จัดกลุ่มเงื่อนไข'],
    ['a*b', 'ดอกจัน — ไวยากรณ์การค้นหา'],
    ['a\\b', 'แบ็กสแลช — ตัวหนีอักขระ'],
  ])('ตัด %s ออก (%s)', (raw) => {
    const out = sanitizeSearch(raw);
    for (const ch of [',', '(', ')', '*', '\\']) expect(out).not.toContain(ch);
  });

  it('คำค้นปกติไม่ถูกแตะ', () => {
    expect(sanitizeSearch('  MCR  ')).toBe('MCR');
    expect(sanitizeSearch('บริษัท ก จำกัด')).toBe('บริษัท ก จำกัด');
  });

  it('ตัดคำค้นที่ยาวผิดปกติ', () => {
    expect(sanitizeSearch('x'.repeat(500)).length).toBe(100);
  });

  it('ช่องว่างซ้ำถูกยุบเหลือช่องเดียว', () => {
    expect(sanitizeSearch('a,,,b')).toBe('a b');
  });
});
