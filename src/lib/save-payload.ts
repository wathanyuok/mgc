// หน้าจอเก็บ "ชื่อ" กับ "รหัส" ของฝ่าย สถานที่ และประเภทธุรกิจ ไว้ในฟอร์มด้วย
// เพื่อเอาไว้แสดงผลเฉยๆ — ฐานข้อมูลเก็บแค่ id เท่านั้น ไม่มีคอลัมน์ชื่อ/รหัส
//
// เดิมหน้าจอส่งทั้งฟอร์มเข้าฐานข้อมูลตรงๆ พอผู้ใช้แตะกล่องจัดประเภทเมื่อไร
// การบันทึกจะพังทันที ขึ้นข้อความดิบว่าหาคอลัมน์ department_code ไม่พบ
// และเกิดกับทุกโมดูลธุรกรรม ไม่ใช่เฉพาะโมดูลเดียว
//
// ตัวช่วยนี้ตัดคีย์ที่มีไว้แสดงผลอย่างเดียวออกก่อนบันทึก
// ส่วนการแสดงชื่อบนหน้าจอหลังเปิดรายการขึ้นมาใหม่ กล่องจัดประเภทจะไปหาชื่อจาก id ให้เอง
// =====================================================================

/** คีย์ที่มีไว้แสดงผลบนหน้าจอเท่านั้น — ห้ามส่งเข้าฐานข้อมูล */
export const DISPLAY_ONLY_KEYS = [
  'department_code', 'department_name',
  'location_code', 'location_name',
  'class_code', 'class_name',
  'subsidiary_code', 'subsidiary_name',
] as const;

/**
 * ตัดคีย์ที่มีไว้แสดงผลออกจากข้อมูลก่อนบันทึก
 * ใช้กับทุกหน้าที่ทำ payload ด้วยการกระจายค่าจากฟอร์มทั้งก้อน
 */
export function toDbPayload<T extends Record<string, any>>(form: T): Omit<T, typeof DISPLAY_ONLY_KEYS[number]> {
  const out: Record<string, any> = { ...form };
  for (const k of DISPLAY_ONLY_KEYS) delete out[k];
  return out as any;
}
