// ส่วนดอกเบี้ย ตอนตั้งค้างจ่ายลงค่าใช้จ่ายไปแล้วรอบหนึ่ง (Dr ค่าใช้จ่าย / Cr ดอกเบี้ยค้างจ่าย)
// พอตัดชำระลงค่าใช้จ่ายซ้ำอีกรอบ → ค่าใช้จ่ายเกินจริง 2 เท่า และยอดค้างจ่ายไม่เคยถูกล้าง
// ที่ถูกคือ ถ้าเคยตั้งค้างจ่ายไว้ ตอนจ่ายต้องล้างยอดค้างจ่าย ไม่ใช่ลงค่าใช้จ่ายใหม่
