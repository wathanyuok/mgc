export interface GLRef {
  code: string;
  name: string;
}

/** บัญชีหนี้สินที่แต่ละชนิดสัญญาตั้งไว้ตอนเบิก */
const PRINCIPAL_GL: Record<string, GLRef> = {
  PN:    { code: '2142102', name: 'ตั๋วสัญญาใช้เงิน (P/N) — สถาบันการเงิน' },
  TR:    { code: '2142109', name: 'เจ้าหนี้ — ทรัสต์รีซีท (T/R)' },
  FP:    { code: '2142109', name: 'เจ้าหนี้ — สินเชื่อสต๊อกรถ (Floor Plan)' },
  OD:    { code: '2142101', name: 'เงินกู้ยืมระยะสั้นสถาบันการเงิน (O/D)' },
  Loan:  { code: '2142101', name: 'เงินกู้ยืมระยะสั้นสถาบันการเงิน' },
};

/** ถ้าไม่รู้จักชนิดสัญญา ใช้บัญชีเงินกู้ยืมระยะสั้นเป็นค่าตั้งต้น (พฤติกรรมเดิม) */
const PRINCIPAL_GL_FALLBACK: GLRef = PRINCIPAL_GL.Loan;

/** บัญชีหนี้สินที่ต้องล้างตอนจ่ายคืนเงินต้น */
export function principalGLFor(facilityType: string | null | undefined): GLRef {
  return PRINCIPAL_GL[String(facilityType ?? '')] ?? PRINCIPAL_GL_FALLBACK;
}

/** ดอกเบี้ยค้างจ่าย — ใช้เมื่อสัญญานั้นเคยตั้งค้างจ่ายไว้แล้ว */
export const ACCRUED_INTEREST_GL: GLRef = {
  code: '2194109',
  name: 'ดอกเบี้ยค้างจ่าย-สถาบันการเงิน',
};

/** ดอกเบี้ยจ่าย — ใช้เมื่อยังไม่เคยตั้งค้างจ่าย จ่ายแล้วรับรู้เป็นค่าใช้จ่ายทันที */
export const INTEREST_EXPENSE_GL: GLRef = {
  code: '5512103',
  name: 'ดอกเบี้ยจ่าย-เงินกู้ยืมระยะสั้น',
};

/** ชนิดใบสำคัญที่แต่ละโมดูลใช้ตอนตั้งดอกเบี้ยค้างจ่าย */
const ACCRUED_SOURCE_TYPE: Record<string, string> = {
  PN:   'PN_ACCRUED',
  TR:   'TR_ACCRUED',
  FP:   'FP_ACCRUED',
  OD:   'OD_ACCRUED',
  Loan: 'LOAN_ACCRUED',
};

export function accruedSourceTypeFor(facilityType: string | null | undefined): string | null {
  return ACCRUED_SOURCE_TYPE[String(facilityType ?? '')] ?? null;
}
