export interface GLRef {
  code: string;
  name: string;
}

/**
 * ชื่อเรียกชนิดสัญญาที่หมายถึงตัวเดียวกัน — รวมให้เหลือรหัสเดียวก่อนค้นตาราง
 *
 * หน้าจอกับฐานข้อมูลเรียกชนิดเดียวกันไม่เหมือนกัน ('Loan' / 'LOAN' / 'loan')
 * ถ้าไม่รวมก่อน จะพลาดไปใช้บัญชีค่าตั้งต้นทั้งที่รู้จักชนิดนั้นอยู่แล้ว
 * (ตั้งใจไม่เรียกตัวรวมชื่อกลาง เพราะไฟล์นั้นดึงตัวเชื่อมฐานข้อมูลกับ React มาด้วย
 *  ไฟล์นี้ต้องเป็นตรรกะล้วนเพื่อให้ชุดทดสอบเรียกได้โดยไม่ต้องต่อฐานข้อมูล)
 */
const CODE_ALIAS: Record<string, string> = {
  'P/N': 'PN', 'O/D': 'OD', 'T/R': 'TR',
  LOAN: 'Loan', loan: 'Loan',
  LEASE: 'Lease', lease: 'Lease',
  'Floor Plan': 'FP', 'FX Forward': 'FXF',
  'Hire Purchase': 'HP',
  // หนังสือค้ำประกันในระบบมีค่าเดียว — 'BG' เป็นชื่อเรียกเก่าของ 'LG'
  BG: 'LG', 'LG/BG': 'LG',
  // เลตเตอร์ออฟเครดิตแบบค้ำประกัน ใช้เส้นทางบัญชีเดียวกับเลตเตอร์ออฟเครดิตปกติ
  SBLC: 'LC',
};

function canonCode(facilityType: string | null | undefined): string {
  const raw = String(facilityType ?? '').trim();
  return CODE_ALIAS[raw] ?? raw;
}

